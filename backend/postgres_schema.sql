CREATE SCHEMA registry;
CREATE SCHEMA journal;

CREATE TABLE registry.schema_version (
    version integer PRIMARY KEY CHECK (version = 1)
);
INSERT INTO registry.schema_version VALUES (1);

CREATE TABLE registry.users (
    telegram_id text PRIMARY KEY,
    name text NOT NULL,
    role text NOT NULL CHECK (role IN ('admin', 'master')),
    enabled smallint NOT NULL DEFAULT 1 CHECK (enabled IN (0, 1)),
    avatar_url text NOT NULL DEFAULT '',
    username text NOT NULL DEFAULT '',
    custom_name smallint NOT NULL DEFAULT 0 CHECK (custom_name IN (0, 1))
);

CREATE TABLE registry.projects (
    id text PRIMARY KEY,
    owner_id text NOT NULL REFERENCES registry.users (telegram_id),
    name text NOT NULL,
    db_path text NOT NULL UNIQUE CHECK (db_path = 'project:' || id),
    created_at timestamptz NOT NULL
);
CREATE INDEX projects_by_owner ON registry.projects (owner_id, created_at DESC);

CREATE TABLE registry.shared_settings (
    key text PRIMARY KEY,
    value text NOT NULL
);

CREATE TABLE registry.reminder_deliveries (
    telegram_id text NOT NULL,
    day date NOT NULL,
    run_key text NOT NULL,
    status text NOT NULL,
    error text,
    created_at timestamptz NOT NULL,
    PRIMARY KEY (telegram_id, day, run_key)
);
CREATE INDEX reminders_by_time ON registry.reminder_deliveries (created_at DESC);

CREATE TABLE registry.profile_avatars (
    telegram_id text PRIMARY KEY,
    content bytea NOT NULL,
    mime text NOT NULL,
    checked_at bigint NOT NULL
);

CREATE TABLE journal.positions (
    project_id text NOT NULL DEFAULT current_setting('journal.project_id', true) REFERENCES registry.projects (id),
    id text NOT NULL,
    name text NOT NULL,
    section text NOT NULL DEFAULT '',
    unit text NOT NULL,
    planned numeric(24,8) NOT NULL,
    rate numeric(24,8) NOT NULL,
    source_row integer,
    source_sheet text NOT NULL DEFAULT '',
    baseline numeric(24,8) NOT NULL DEFAULT 0,
    PRIMARY KEY (project_id, id)
);

CREATE TABLE journal.entries (
    project_id text NOT NULL DEFAULT current_setting('journal.project_id', true),
    item_id text NOT NULL,
    date date NOT NULL,
    quantity numeric(24,8) NOT NULL,
    PRIMARY KEY (project_id, item_id, date),
    FOREIGN KEY (project_id, item_id) REFERENCES journal.positions (project_id, id)
);
CREATE INDEX entries_by_date ON journal.entries (project_id, date, item_id);

CREATE TABLE journal.reports (
    project_id text NOT NULL DEFAULT current_setting('journal.project_id', true) REFERENCES registry.projects (id),
    date date NOT NULL,
    revision integer NOT NULL DEFAULT 0,
    text text,
    updated_at timestamptz,
    sync_status text NOT NULL DEFAULT 'local',
    crew_count integer NOT NULL DEFAULT 1,
    sync_error text NOT NULL DEFAULT '',
    author_id text NOT NULL DEFAULT '',
    sync_attempts integer NOT NULL DEFAULT 0,
    retry_at text NOT NULL DEFAULT '',
    PRIMARY KEY (project_id, date)
);
CREATE INDEX reports_for_retry ON journal.reports (project_id, sync_status, retry_at, date);

CREATE TABLE journal.audit (
    project_id text NOT NULL DEFAULT current_setting('journal.project_id', true) REFERENCES registry.projects (id),
    id bigint GENERATED BY DEFAULT AS IDENTITY,
    date date NOT NULL,
    payload jsonb NOT NULL,
    created_at timestamptz NOT NULL,
    PRIMARY KEY (project_id, id)
);
CREATE INDEX audit_by_date ON journal.audit (project_id, date, id);

CREATE TABLE journal.settings (
    project_id text NOT NULL DEFAULT current_setting('journal.project_id', true) REFERENCES registry.projects (id),
    key text NOT NULL,
    value text,
    PRIMARY KEY (project_id, key)
);

CREATE TABLE journal.day_snapshots (
    project_id text NOT NULL DEFAULT current_setting('journal.project_id', true) REFERENCES registry.projects (id),
    date date NOT NULL,
    payload jsonb NOT NULL,
    created_at timestamptz NOT NULL,
    PRIMARY KEY (project_id, date)
);

DO $$
DECLARE
    relation text;
BEGIN
    FOREACH relation IN ARRAY ARRAY['positions','entries','reports','audit','settings','day_snapshots']
    LOOP
        EXECUTE format('ALTER TABLE journal.%I ENABLE ROW LEVEL SECURITY', relation);
        EXECUTE format('ALTER TABLE journal.%I FORCE ROW LEVEL SECURITY', relation);
        EXECUTE format(
            'CREATE POLICY active_project ON journal.%I USING (project_id = current_setting(''journal.project_id'', true)) WITH CHECK (project_id = current_setting(''journal.project_id'', true))',
            relation
        );
    END LOOP;
END $$;
